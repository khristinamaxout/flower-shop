export let products = loadProducts(defaultProducts);

export function reloadProducts() {
  products = loadProducts(defaultProducts);
  return products;
}

export function saveAllProducts(list) {
  products = list;
  persistProducts(list);
}

export function filterByGiftFinder({ recipient, occasion, budget }) {
  return activeProducts().filter((product) => {
    const matchesRecipient = !recipient || product.tags.includes(recipient);
    const matchesOccasion = !occasion || product.tags.includes(occasion);
    const matchesBudget = !budget || product.price <= budget;
    return matchesRecipient && matchesOccasion && matchesBudget;
  });
}

function activeProducts() {
  return products.filter((p) => p.available !== false);
}

export function filterByScenario(scenarioTags) {
  return activeProducts().filter((product) =>
    product.tags.some((tag) => scenarioTags.includes(tag))
  );
}

export function filterByBudget(maxBudget) {
  return activeProducts().filter((p) => p.price <= maxBudget);
}

export function getSeasonalProducts() {
  return activeProducts().filter((p) => p.seasonal);
}

export function getBestsellers(limit = 8) {
  return activeProducts().filter((p) => p.bestseller).slice(0, limit);
}

export function getByCategory(categoryId) {
  return activeProducts().filter((p) => p.category === categoryId);
}

export function getProductById(id) {
  return activeProducts().find((p) => p.id === id);
}

